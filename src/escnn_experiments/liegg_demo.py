"""
LieGG DISCOVERS the group instead of assuming it -- and that is the difference.

so2_exact_lee_reversal_demo.py shows LEE ranking a provably SO(2)-equivariant
model LAST and an UNTRAINED network FIRST, with no lattice to blame. The obvious
rebuttal is that this indicts one particular convention -- Gruver et al.'s
fallback of assuming the trivial representation for a non-image tensor -- rather
than rho-dependent measurement as such. LieGG (Moskalev, Sepliarskaia, Sosnovik &
Smeulders, "LieGG: Studying Learned Lie Group Generators", NeurIPS 2022) is the
strongest form of that rebuttal, so this script runs it on the same models.

THE METHOD. For a network f invariant to the one-parameter group generated by A,
acting on the input as x -> exp(tA)x, differentiating f(exp(tA)x) at t=0 gives

    grad f(x)^T A x = 0     for every x,

which is LINEAR in the entries of A, since grad f(x)^T A x = <A, grad f(x) x^T>.
Stack one row vec(grad f(x_i) x_i^T) per sample and the NULL SPACE of the
resulting polarization matrix E is the algebra of generators the network is
invariant to. The group is read out of the network; nothing is supplied. Here the
input is 8 points x 2 coords = 16 dims and the true generator is I_8 (x) J with
J = [[0,-1],[1,0]] -- block diagonal, one J per point.

THE SETTING is deliberately LieGG's best case: the SO(2) action on a point cloud
is an exact orthogonal matmul (linear in the input, as the derivation requires)
and the target is an exactly invariant scalar (so the trivial-representation
condition above holds by construction). If LieGG cannot succeed here it cannot
succeed anywhere. A fourth model is added that the host demo lacks -- the same
MLP trained with NO augmentation -- because a symmetry-DISCOVERY method must be
shown finding nothing when there is nothing.

MEASURED (3 seeds, 300 epochs, n=2048, null tol 0.05).

  model                   sym_var  null_dim   align    |grad|   LEE naive  1-CKA
  EquivariantSO2          0.00000       1.0  1.0000    5.9228      0.9999  0.000000
  LearnedMLP (aug)        0.05760       0.0  0.0000    5.9187      0.3702  0.008651
  LearnedMLP (NO aug)     0.06845       0.0  0.0000    6.1034      0.6413  0.042468
  LearnedMLP (untrained)  0.16950       0.0  0.0000    0.0083      0.2518  0.460116

1. LIEGG RECOVERS SO(2) EXACTLY, WITHOUT BEING TOLD IT. For the equivariant
   model the smallest normalized singular value is 0.00000, the numerical null
   space has dimension exactly 1 -- SO(2) is one-dimensional -- and its
   alignment with the true I_8 (x) J is 1.0000. The generator came out of the
   network. This is the thing LEE cannot do, and it is a real result for the
   rho-dependent family.

2. IT IS NOT FOOLED BY THE DEGENERACY THAT INVERTS LEE, AND THE MECHANISM IS
   VISIBLE. Ranking by symmetry variance (lower = more symmetric):

       LieGG    equivariant 0.00000 < aug 0.05760 < no-aug 0.06845 < untrained 0.16950
       LEE      untrained   0.2518  < aug 0.3702  < no-aug 0.6413  < equivariant 0.9999

   LieGG puts the untrained network LAST where LEE puts it FIRST. The |grad|
   column is why: the untrained model's polarization matrix is 0.0083 against
   ~5.9 for the others, a 713x smaller signal. LEE divides by ||f(x)||, so a
   network whose features barely respond gets a small numerator and looks
   equivariant; LieGG uses the spectrum of E normalized by its own largest
   singular value, so scaling every gradient down cancels exactly and constancy
   buys nothing. That is the whole difference between the two, in one column.

3. BUT ITS BINARY VERDICT RIDES ON A HAND-SET THRESHOLD. null_dim and align are
   computed at sigma/sigma_max < 0.05, and the augmented MLP lands at 0.05760 --
   just above. So at 300 epochs LieGG reports "no symmetry" for a model trained
   with full SO(2) augmentation whose CKA error is 0.0087 and whose predictions
   drift only 9.9%. At 60 epochs (1 seed) the same model measured 0.04163, just
   BELOW, and LieGG reported null_dim 1 with align 0.9498 -- a recovered
   generator. The qualitative verdict flips on a 15% change in a constant nobody
   derived. This is the same species of knob as RBF CKA's bandwidth
   (unlearnable_rho_demo.py) and plug-in MI's granularity
   (metric_demos/exact_mi_demo.py): a resolution parameter that decides the
   answer. Report the continuous sym_var, not the thresholded null_dim.

4. AND IT IS WEAKLY DISCRIMINATIVE AMONG APPROXIMATE SYMMETRIES. Separation
   between the augmented and the non-augmented MLP -- the comparison the whole
   sweep in src/ is built on:

       LieGG sym_var   0.05760 vs 0.06845    1.19x
       drift (truth)   0.0989  vs 0.2283     2.31x
       1 - linear CKA  0.00865 vs 0.04247    4.91x

   LieGG is superb at certifying an EXACT symmetry (0.00000, and it names the
   generator) and nearly blind between two approximate ones, where linear CKA
   separates more sharply than the behavioural ground truth does. The two
   methods are answering different questions and the right one depends on which
   you have: a model with an exact symmetry to certify, or two trained models to
   rank.

   The SHARED 2x2 variant sharpens the point. Assuming additionally that the
   action is identical on every point drops the unknowns from 256 to 4 and makes
   the test much stricter -- equivariant 0.00000, aug 0.23208, no-aug 0.38692,
   untrained 0.73278 -- so it separates better (1.67x) but now only the exactly
   equivariant model registers as symmetric at all. Tightening the hypothesis
   class trades sensitivity for specificity, exactly as fitting rho(g) does in
   family B.

WHAT LIEGG ASSUMES, since the point of this folder is that every metric assumes
something:

  * THE GROUP ACTS LINEARLY ON THE INPUT. The derivation needs x -> exp(tA)x.
    True here by construction. NOT true of image rotation acting on pixel
    values, which is why LieGG treats images through a separate construction --
    so this result does not transfer to the grid experiments in this folder.
  * THE OUTPUT IS INVARIANT. grad f(x)^T A x = 0 IS the trivial-representation
    assumption -- the same one that makes LEE fail here. It holds in this script
    because the target is an invariant scalar, i.e. it is granted by the task,
    not by the method. For an equivariant vector-valued output the condition
    needs extending, and the extension needs to know how the output transforms.
  * A NULL-SPACE THRESHOLD, per finding 3.
  * WHITE-BOX GRADIENT ACCESS and differentiability.

  And it answers a DIFFERENT QUESTION: what input-space symmetry does this
  network have? Not: is this hidden layer equivariant? It never touches the
  96-dim hidden representation that LEE and CKA are scored on elsewhere, so it
  is not a replacement for either -- it is a better-posed version of the
  question family A was trying to ask.

CONCLUSION, and it narrows this folder's claim rather than supporting it. "Metrics
that depend on rho(g) fail" is too strong: LieGG depends on rho(g) in the sense
of needing a group action, recovers it correctly, and beats LEE on every row
here. The defensible claim is narrower and about WHERE the assumption sits:

    LEE needs rho(g) SPECIFIED in feature space, and supplies a wrong default.
    LieGG needs the action to be LINEAR ON THE INPUT and the output INVARIANT,
      and derives the rest.
    Linear CKA needs rho(g) only to BE an isometry, which a group
      representation on feature channels is by construction.

Run: cd src/escnn_experiments && .venv/bin/python3 liegg_demo.py
     (--seeds / --epochs to match so2_exact_lee_reversal_demo.py; needs no escnn)
"""
import argparse
import math
import sys
from pathlib import Path

import torch
import torch.nn.functional as F

sys.path.insert(0, str(Path(__file__).resolve().parent))
from so2_exact_lee_reversal_demo import (  # noqa: E402
    ANGLES, DEVICE, K, N_EVAL, N_TRAIN, EquivariantSO2, LearnedMLP, cka_error,
    invariant_target, lee_naive, pred_drift, sample_clouds, train)

DIM = 2 * K                      # 16-dim input: 8 points x 2 coords
NULL_TOL = 0.05                  # sigma/sigma_max below this counts as null


def true_generator():
    """The SO(2) generator on the full input space. Rotation acts on every point
    identically, so on R^16 the generator is I_8 (x) J with J = [[0,-1],[1,0]]:
    block diagonal, one J per point."""
    J = torch.tensor([[0.0, -1.0], [1.0, 0.0]])
    return torch.block_diag(*([J] * K))


# ------------------------------------------------------------------ LieGG

def polarization(model, p, restrict_shared=False):
    """LieGG's network polarization matrix (Moskalev et al., NeurIPS 2022).

    For a network f invariant under the one-parameter group generated by A,
    acting on the input as x -> exp(tA)x, differentiating f(exp(tA)x) at t=0
    gives the exact condition

        grad f(x)^T A x = 0     for every x,

    which is LINEAR in the entries of A: grad f(x)^T A x = <A, grad f(x) x^T>.
    So stacking one row vec(grad f(x_i) x_i^T) per sample builds a matrix E
    whose NULL SPACE is the set of generators the network is invariant to. The
    group is recovered from the network, never supplied -- which is exactly the
    property LEE lacks and the reason this script exists.

    restrict_shared additionally assumes the group acts identically on every
    point, i.e. A = I_K (x) B for an unknown 2x2 B, which collapses the unknowns
    from 256 to 4. That is a strictly stronger assumption about the input
    structure, and it is reported separately for precisely that reason."""
    p = p.clone().detach().requires_grad_(True)
    out = model(p)[0]
    g, = torch.autograd.grad(out.sum(), p)          # (B, K, 2), f is scalar
    if restrict_shared:
        # sum_i grad_{p_i} f p_i^T -- the shared 2x2 block's coefficient
        E = torch.einsum("bkj,bkl->bjl", g, p.detach())
        return E.reshape(len(p), 4)
    gf, xf = g.reshape(len(p), -1), p.detach().reshape(len(p), -1)
    return (gf[:, :, None] * xf[:, None, :]).reshape(len(p), -1)


def liegg(model, p, A_true, restrict_shared=False):
    """Run LieGG and score it three ways.

    symmetry_variance   smallest normalized singular value of E. LieGG's own
                        measure of how exactly SOME one-parameter symmetry
                        holds. ~0 means a generator was found.
    null_dim            how many directions sit below NULL_TOL, i.e. the
                        dimension of the recovered symmetry algebra. SO(2) is
                        one-dimensional, so anything above 1 means the
                        constraints did not pin the group down.
    true_gen_residual   ||E vec(A_true)|| / (sigma_max ||vec(A_true)||): does
                        the TRUE SO(2) generator satisfy the learned
                        constraints? This is the part that cannot be faked by a
                        degenerate network, because it names A_true instead of
                        letting the model choose.
    alignment           |cos| between the recovered generator and A_true, taken
                        over the whole numerical null space rather than just the
                        last singular vector (the null space may be >1-D, in
                        which case any single basis vector is arbitrary)."""
    E = polarization(model, p, restrict_shared)
    A = (A_true.reshape(-1) if not restrict_shared
         else torch.tensor([0.0, -1.0, 1.0, 0.0]))
    A = A.to(E.device) / A.norm()
    U, S, Vh = torch.linalg.svd(E, full_matrices=False)
    smax = S[0].clamp_min(1e-30)
    Sn = S / smax
    null = Vh[Sn < NULL_TOL]                        # (k, d^2) orthonormal rows
    if len(null):
        # fraction of A_true's norm captured by the recovered null space
        align = (null @ A).norm().clamp(max=1.0).item()
    else:
        align = 0.0
    return {"sym_var": Sn[-1].item(),
            "null_dim": int((Sn < NULL_TOL).sum().item()),
            "true_res": ((E @ A).norm() / smax).item() / math.sqrt(len(E)),
            "align": align,
            "grad_scale": E.norm().item() / math.sqrt(len(E))}


# ------------------------------------------------------------------ models

def build(p_tr, y_tr, epochs, seed):
    """The three models from so2_exact_lee_reversal_demo, plus a fourth: the
    same MLP trained with NO augmentation. The original demo augments both
    models, so it has no genuinely non-invariant control -- and a symmetry
    DISCOVERY method has to be shown to find nothing when there is nothing."""
    eq = train(EquivariantSO2().to(DEVICE), p_tr, y_tr, epochs, seed)
    ml = train(LearnedMLP().to(DEVICE), p_tr, y_tr, epochs, seed)
    torch.manual_seed(seed)
    un = LearnedMLP().to(DEVICE).eval()
    na = train_noaug(LearnedMLP().to(DEVICE), p_tr, y_tr, epochs, seed)
    return [("EquivariantSO2", eq), ("LearnedMLP (aug)", ml),
            ("LearnedMLP (NO aug)", na), ("LearnedMLP (untrained)", un)]


def train_noaug(model, p, y, epochs, seed):
    """Identical to train() but without the rotation augmentation, so the model
    has no reason to become invariant. The target still is."""
    torch.manual_seed(seed)
    gen = torch.Generator().manual_seed(seed + 1)
    opt = torch.optim.Adam(model.parameters(), 2e-3)
    model.train()
    for _ in range(epochs):
        perm = torch.randperm(p.shape[0], generator=gen)
        for i in range(0, p.shape[0], 256):
            idx = perm[i:i + 256]
            opt.zero_grad()
            F.mse_loss(model(p[idx])[0], y[idx]).backward()
            opt.step()
    return model.eval()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--epochs", type=int, default=300)
    ap.add_argument("--seeds", type=int, default=3)
    args = ap.parse_args()
    A_true = true_generator().to(DEVICE)

    acc = {}
    for seed in range(args.seeds):
        gen = torch.Generator().manual_seed(seed)
        p_tr = sample_clouds(N_TRAIN, gen).to(DEVICE)
        p_ev = sample_clouds(N_EVAL, gen).to(DEVICE)
        y_tr, y_ev = invariant_target(p_tr), invariant_target(p_ev)
        mu, sd = y_tr.mean(), y_tr.std()
        y_tr, y_ev = (y_tr - mu) / sd, (y_ev - mu) / sd

        for name, m in build(p_tr, y_tr, args.epochs, seed):
            full = liegg(m, p_ev, A_true, restrict_shared=False)
            shar = liegg(m, p_ev, A_true, restrict_shared=True)
            row = dict(mse=F.mse_loss(m(p_ev)[0], y_ev).item(),
                       lee=lee_naive(m, p_ev),
                       cka=sum(cka_error(m, p_ev, d) for d in ANGLES) / len(ANGLES),
                       drift=sum(pred_drift(m, p_ev, d) for d in ANGLES) / len(ANGLES),
                       **{f"f_{k}": v for k, v in full.items()},
                       **{f"s_{k}": v for k, v in shar.items()})
            acc.setdefault(name, []).append(row)

    mean = lambda n, k: sum(r[k] for r in acc[n]) / len(acc[n])
    print("\nLieGG vs LEE vs linear CKA, exact SO(2) on 2D point clouds")
    print(f"{args.seeds} seeds, {args.epochs} epochs, n={N_EVAL}, "
          f"input dim {DIM}, null tol {NULL_TOL}\n")

    print("=" * 100)
    print("  LieGG, FULL 16x16 generator search (256 unknowns, assumes only a "
          "linear action on the input)")
    print("=" * 100)
    print(f"  {'model':<24s} {'sym_var':>8s} {'null_dim':>9s} {'true_res':>9s} "
          f"{'align':>7s} {'|grad|':>8s} {'test MSE':>9s}")
    for n in acc:
        print(f"  {n:<24s} {mean(n,'f_sym_var'):8.5f} {mean(n,'f_null_dim'):9.1f} "
              f"{mean(n,'f_true_res'):9.5f} {mean(n,'f_align'):7.4f} "
              f"{mean(n,'f_grad_scale'):8.4f} {mean(n,'mse'):9.5f}")

    print("\n" + "=" * 100)
    print("  LieGG, SHARED 2x2 block (4 unknowns; additionally assumes the "
          "action is identical per point)")
    print("=" * 100)
    print(f"  {'model':<24s} {'sym_var':>8s} {'null_dim':>9s} {'true_res':>9s} "
          f"{'align':>7s}")
    for n in acc:
        print(f"  {n:<24s} {mean(n,'s_sym_var'):8.5f} {mean(n,'s_null_dim'):9.1f} "
              f"{mean(n,'s_true_res'):9.5f} {mean(n,'s_align'):7.4f}")

    print("\n" + "=" * 100)
    print("  head to head: does each metric rank the four models correctly?")
    print("=" * 100)
    print(f"  {'model':<24s} {'LieGG true_res':>15s} {'LEE naive':>10s} "
          f"{'1-CKA':>9s} {'drift':>9s} {'test MSE':>9s}")
    for n in acc:
        print(f"  {n:<24s} {mean(n,'s_true_res'):15.5f} {mean(n,'lee'):10.4f} "
              f"{mean(n,'cka'):9.6f} {mean(n,'drift'):9.6f} {mean(n,'mse'):9.5f}")
    order = lambda k: " < ".join(n for n, _ in sorted(
        ((n, mean(n, k)) for n in acc), key=lambda t: t[1]))
    print("\n  ranking (lower first):")
    for label, k in [("LieGG true_res", "s_true_res"), ("LEE naive", "lee"),
                     ("1 - linear CKA", "cka"), ("drift (ground truth)", "drift")]:
        print(f"    {label:<22s} {order(k)}")


if __name__ == "__main__":
    main()
